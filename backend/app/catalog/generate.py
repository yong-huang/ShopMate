"""Mock catalog generator and build check (ticket T02, System Design 3.8).

Produces ``products.json`` plus deterministic SVG placeholder images into
``backend/data/catalog/``. The committed data is generated by this module
via ``make catalog``; the demo therefore works without regenerating.

- 150 products total: Electronics 30, Home & Kitchen 40,
  Apparel & Accessories 40, Sports & Outdoors 40.
- The first 30 records (spread across all four categories) are the
  hand-curated rich records in ``curated.py``; the remaining 120 are
  template-generated from ``templates.py`` with a fixed seed, so output
  is byte-for-byte deterministic.
- Images: SVG placeholders with a category emoji and a stable palette
  index derived from the product id (crc32, not ``hash()``, which is
  process-randomized). No external image sources.

Usage::

    uv run python -m app.catalog.generate          # regenerate
    uv run python -m app.catalog.generate --check  # build check only
"""

import argparse
import json
import random
import re
import unicodedata
import xml.sax.saxutils as saxutils
import zlib
from pathlib import Path
from typing import Any

from app.catalog.curated import CURATED_PRODUCTS
from app.catalog.templates import (
    BRANDS,
    CATEGORY_META,
    CATEGORY_ORDER,
    COLOURS,
    DESCRIPTION_TEMPLATES,
    FEATURE_POOL,
    PRICE_JITTER,
    PRODUCT_TYPES,
    REVIEW_TEMPLATES,
    SPEC_SHEETS,
    USE_POOL,
)

GENERATION_SEED = 20260215
EXPECTED_TOTAL = 150
EXPECTED_FEATURED = 30

CATEGORY_SPLITS: dict[str, int] = {
    "Electronics": 30,
    "Home & Kitchen": 40,
    "Apparel & Accessories": 40,
    "Sports & Outdoors": 40,
}

# Stable 8-color palette for the generated SVGs; index = crc32(id) % 8.
PALETTE: list[tuple[str, str]] = [
    ("#4f46e5", "#a5b4fc"),
    ("#0f766e", "#5eead4"),
    ("#b45309", "#fcd34d"),
    ("#be185d", "#f9a8d4"),
    ("#1d4ed8", "#93c5fd"),
    ("#047857", "#6ee7b7"),
    ("#7c3aed", "#c4b5fd"),
    ("#b91c1c", "#fca5a5"),
]


def slugify(text: str) -> str:
    """Kebab-case a product name into a URL-safe slug."""
    normalized = unicodedata.normalize("NFKD", text)
    ascii_only = normalized.encode("ascii", "ignore").decode("ascii")
    return re.sub(r"-{2,}", "-", re.sub(r"[^a-z0-9]+", "-", ascii_only.lower())).strip("-")


def render_svg(product_id: str, emoji: str, label: str, category: str) -> str:
    """Render the deterministic SVG placeholder for one product."""
    base, light = PALETTE[zlib.crc32(product_id.encode("utf-8")) % len(PALETTE)]
    escaped_label = saxutils.escape(label)
    escaped_category = saxutils.escape(category)
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="640" height="640" '
        'viewBox="0 0 640 640" role="img" '
        f'aria-label="{escaped_label}">\n'
        "  <defs>\n"
        f'    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">\n'
        f'      <stop offset="0%" stop-color="{light}"/>\n'
        f'      <stop offset="100%" stop-color="{base}"/>\n'
        "    </linearGradient>\n"
        "  </defs>\n"
        '  <rect width="640" height="640" fill="url(#bg)" rx="24"/>\n'
        '  <circle cx="320" cy="270" r="120" fill="rgba(255,255,255,0.25)"/>\n'
        '  <text x="320" y="316" font-size="110" text-anchor="middle" '
        f'>{saxutils.escape(emoji)}</text>\n'
        '  <text x="320" y="480" font-size="30" font-family="system-ui, '
        'sans-serif" font-weight="600" fill="#ffffff" text-anchor="middle">'
        f"{escaped_label}</text>\n"
        '  <text x="320" y="530" font-size="22" font-family="system-ui, '
        'sans-serif" fill="rgba(255,255,255,0.85)" text-anchor="middle">'
        f"{saxutils.escape(category)} · {saxutils.escape(product_id)}</text>\n"
        "</svg>\n"
    )


def _templated_record(rng: random.Random, category: str, id_: str, seq: int,
                      type_spec: dict[str, Any], used_slugs: set[str]
                      ) -> dict[str, Any]:
    """Generate one templated product from the fixed pools."""
    brand = rng.choice(BRANDS[category])
    colour = rng.choice(COLOURS[category])
    display_en = f"{brand} {type_spec['name_en']}"
    display_zh = f"{brand} {type_spec['name_zh']}"

    slug = slugify(display_en)
    suffix = 2
    while slug in used_slugs:
        slug = f"{slugify(display_en)}-{suffix}"
        suffix += 1
    used_slugs.add(slug)

    feature = rng.choice(FEATURE_POOL)
    use = rng.choice(USE_POOL)
    template = rng.choice(DESCRIPTION_TEMPLATES)
    description_en = template["en"].format(
        brand=brand, name_en=display_en, name_zh=display_zh,
        feature_en=feature["en"], feature_zh=feature["zh"],
        use_en=use["en"], use_zh=use["zh"],
    )
    description_zh = template["zh"].format(
        brand=brand, name_en=display_en, name_zh=display_zh,
        feature_en=feature["en"], feature_zh=feature["zh"],
        use_en=use["en"], use_zh=use["zh"],
    )

    specs = [
        {"label": label, "value": rng.choice(options)}
        for label, options in SPEC_SHEETS[category]
    ]
    warranty = next(
        (spec["value"] for spec in specs if spec["label"] == "Warranty"),
        "12 months",
    )

    sample = rng.sample(REVIEW_TEMPLATES, rng.choice([1, 2]))
    reviews = [dict(review) for review in sample]

    price = round(type_spec["price"] * (1 + rng.uniform(-PRICE_JITTER, PRICE_JITTER)), 2)
    initials = "".join(word[0] for word in type_spec["name_en"].split()[:3]).upper()

    product: dict[str, Any] = {
        "id": id_,
        "slug": slug,
        "name_en": display_en,
        "name_zh": display_zh,
        "description_en": description_en,
        "description_zh": description_zh,
        "category": category,
        "price": price,
        "currency": "USD",
        "attributes": {
            "brand": brand,
            "model": f"{initials}-{seq:03d}",
            "colour": colour,
            "warranty": warranty,
        },
        "specs": specs,
        "reviews": reviews,
        "rating": round(sum(r["rating"] for r in reviews) / len(reviews), 1),
        "stock": rng.randint(20, 500),
        "tags": list(type_spec["tags"]),
        "featured": False,
        "image": f"images/{id_}.svg",
    }
    if category == "Apparel & Accessories":
        product.update(_apparel_fields(rng, specs))
    return product


def _apparel_fields(rng: random.Random, specs: list[dict[str, str]]
                    ) -> dict[str, Any]:
    """Build sizing / care / materials for a templated apparel product."""
    garment = rng.choice([
        ("top", ["XS", "S", "M", "L", "XL", "XXL"]),
        ("bottoms", ["26", "28", "30", "32", "34", "36"]),
        ("shoes", ["EU 38", "EU 39", "EU 40", "EU 41", "EU 42",
                   "EU 43", "EU 44"]),
    ])
    material = next(
        (spec["value"] for spec in specs if spec["label"] == "Material"),
        "Cotton blend",
    )
    care = next((spec["value"] for spec in specs if spec["label"] == "Care"),
                "Machine wash cold")
    return {
        "sizing": {"sizes": garment[1],
                   "fit": f"{garment[0].title()} sizing, true to size"},
        "care": f"{care}; do not bleach.",
        "materials": {"shell": material},
    }


def build_products() -> list[dict[str, Any]]:
    """Assemble the full 150-product catalog deterministically."""
    rng = random.Random(GENERATION_SEED)
    used_slugs: set[str] = {p["slug"] for p in CURATED_PRODUCTS}
    curated_by_category: dict[str, int] = {}
    for product in CURATED_PRODUCTS:
        curated_by_category[product["category"]] = (
            curated_by_category.get(product["category"], 0) + 1
        )

    products: list[dict[str, Any]] = list(CURATED_PRODUCTS)
    for category in CATEGORY_ORDER:
        prefix = CATEGORY_META[category]["prefix"]
        seq = curated_by_category.get(category, 0)
        for type_spec in PRODUCT_TYPES[category]:
            seq += 1
            products.append(_templated_record(
                rng, category, f"{prefix}-{seq:03d}", seq, type_spec, used_slugs
            ))
    return products


def generate_catalog(output_dir: Path) -> list[dict[str, Any]]:
    """Write products.json and the SVG images into ``output_dir``."""
    products = build_products()
    output_dir.mkdir(parents=True, exist_ok=True)
    images_dir = output_dir / "images"
    if images_dir.exists():
        for stale in images_dir.iterdir():
            stale.unlink()
    else:
        images_dir.mkdir(parents=True)

    for product in products:
        meta = CATEGORY_META[product["category"]]
        svg = render_svg(
            product["id"], meta["emoji"], product["name_en"], product["category"]
        )
        (images_dir / f"{product['id']}.svg").write_text(svg, encoding="utf-8")

    (output_dir / "products.json").write_text(
        json.dumps(products, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    return products


def check_catalog(catalog_dir: Path) -> list[str]:
    """Validate a generated catalog; returns a list of problems (empty = ok).

    The build check asserts the System Design 3.8 contract: total count,
    per-category split (30/40/40/40), bilingual fields, review minimums,
    price/rating sanity, unique ids and slugs, and image presence.
    """
    problems: list[str] = []
    products_path = catalog_dir / "products.json"
    if not products_path.is_file():
        return [f"{products_path} is missing; run `make catalog` first"]

    try:
        products = json.loads(products_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        return [f"{products_path} is not valid JSON: {error}"]

    if len(products) != EXPECTED_TOTAL:
        problems.append(
            f"Total product count is {len(products)}, expected {EXPECTED_TOTAL}"
        )
    counts: dict[str, int] = {}
    for product in products:
        category = product.get("category", "<missing>")
        counts[category] = counts.get(category, 0) + 1
    if counts != CATEGORY_SPLITS:
        problems.append(
            f"Category split mismatch: {counts}, expected {CATEGORY_SPLITS}"
        )

    seen_ids: set[str] = set()
    seen_slugs: set[str] = set()
    for product in products:
        pid = product.get("id", "<missing>")
        for field in ("name_en", "name_zh", "description_en", "description_zh"):
            value = product.get(field)
            if not isinstance(value, str) or not value.strip():
                problems.append(f"{pid}: {field} must be a non-empty string")
        if product["id"] in seen_ids:
            problems.append(f"{pid}: duplicate id")
        seen_ids.add(product["id"])
        if product.get("slug") in seen_slugs:
            problems.append(f"{pid}: duplicate slug")
        seen_slugs.add(product.get("slug", ""))
        price = product.get("price", 0)
        if not isinstance(price, (int, float)) or price <= 0:
            problems.append(f"{pid}: price must be positive")
        rating = product.get("rating", 0)
        if not isinstance(rating, (int, float)) or not 0 < rating <= 5:
            problems.append(f"{pid}: rating must be in (0, 5]")
        reviews = product.get("reviews") or []
        minimum = 3 if product.get("featured") else 1
        if len(reviews) < minimum:
            problems.append(
                f"{pid}: has {len(reviews)} reviews, needs >= {minimum}"
            )
        if not product.get("tags"):
            problems.append(f"{pid}: tags must not be empty")
        image = product.get("image")
        if not image or not (catalog_dir / image).is_file():
            problems.append(f"{pid}: image {image!r} is missing on disk")
    return problems


def default_catalog_dir() -> Path:
    """backend/data/catalog, resolved from this file's location."""
    return Path(__file__).resolve().parents[2] / "data" / "catalog"


def main() -> int:
    """CLI entry point: regenerate the catalog or run the build check."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true",
        help="validate the existing catalog instead of regenerating it",
    )
    parser.add_argument(
        "--dir", type=Path, default=None,
        help="catalog directory (default: backend/data/catalog)",
    )
    args = parser.parse_args()
    catalog_dir = args.dir if args.dir is not None else default_catalog_dir()

    if args.check:
        problems = check_catalog(catalog_dir)
        if problems:
            print(f"Catalog check FAILED ({len(problems)} problems):")
            for problem in problems:
                print(f"  - {problem}")
            return 1
        print(f"Catalog check OK: {catalog_dir}")
        return 0

    products = generate_catalog(catalog_dir)
    counts: dict[str, int] = {}
    for product in products:
        counts[product["category"]] = counts.get(product["category"], 0) + 1
    print(f"Generated {len(products)} products into {catalog_dir}: {counts}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
